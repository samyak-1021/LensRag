"""Run the evaluation and write ``data/eval/summary.json`` for the dashboard.

Usage:
    python -m app.eval.runner            # offline (mock providers)
    LENSRAG_LLM_PROVIDER=gemini LENSRAG_GEMINI_API_KEY=... python -m app.eval.runner

The runner ingests the committed synthetic corpus into a throwaway database, asks
every question in both text and visual mode, and aggregates the metrics. It sets
its own DB + storage paths *before* importing the app so the real dev database is
never touched.
"""

from __future__ import annotations

import asyncio
import json
import os
import shutil
from datetime import UTC, datetime
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[2]
CORPUS_DIR = BACKEND_DIR / "data" / "corpus"
QA_PATH = BACKEND_DIR / "data" / "eval" / "qa.jsonl"
SUMMARY_PATH = BACKEND_DIR / "data" / "eval" / "summary.json"


def _configure_env() -> Path:
    """Point the app at a throwaway DB + storage dir. Must run before app imports."""
    run_dir = BACKEND_DIR / "eval_runs"
    if run_dir.exists():
        shutil.rmtree(run_dir)
    (run_dir / "storage").mkdir(parents=True)
    os.environ.setdefault(
        "LENSRAG_DATABASE_URL", f"sqlite+aiosqlite:///{run_dir / 'eval.db'}"
    )
    os.environ.setdefault("LENSRAG_STORAGE_DIR", str(run_dir / "storage"))
    return run_dir


async def _evaluate() -> dict:
    # Imported here so the env overrides above take effect first.
    from app.db import SessionLocal, init_db
    from app.eval.dataset import load_questions
    from app.eval.metrics import is_correct, retrieval_hit
    from app.services.ingest import ingest_pdf
    from app.services.providers import get_provider
    from app.services.rag import answer_text, answer_visual

    await init_db()

    questions = load_questions(QA_PATH)
    provider_name = get_provider().name

    async with SessionLocal() as session:
        # Ingest the corpus once; map filename -> document id for gold lookups.
        doc_ids: dict[str, str] = {}
        for pdf_path in sorted(CORPUS_DIR.glob("*.pdf")):
            document = await ingest_pdf(session, pdf_path.read_bytes(), pdf_path.name)
            doc_ids[pdf_path.name] = document.id

        # Buckets of (text_correct, visual_correct, text_recall, visual_recall).
        rows = []
        correct_abstentions = 0
        unanswerable_total = 0
        for q in questions:
            doc_id = doc_ids.get(q.gold_doc)  # None for unanswerable "not present" docs
            text = await answer_text(session, q.question, None, 5)
            visual = await answer_visual(session, q.question, None, 5)
            rows.append(
                {
                    "q": q,
                    "text_ok": is_correct(q, text),
                    "visual_ok": is_correct(q, visual),
                    "text_recall": retrieval_hit(q, text.citations),
                    "visual_recall": retrieval_hit(q, visual.citations),
                }
            )
            if q.unanswerable:
                unanswerable_total += 1
                if visual.abstained:
                    correct_abstentions += 1
            _ = doc_id  # gold doc is resolved for completeness / future per-doc metrics

    return _aggregate(rows, correct_abstentions, unanswerable_total, provider_name, len(questions))


def _aggregate(rows, correct_abstentions, unanswerable_total, provider_name, n) -> dict:
    from app.eval.metrics import rate

    def subset(pred):
        return [r for r in rows if pred(r["q"])]

    visual_qs = subset(lambda q: q.requires_visual and not q.unanswerable)
    text_qs = subset(lambda q: not q.requires_visual and not q.unanswerable)
    answerable = subset(lambda q: not q.unanswerable)

    def acc(bucket, key):
        return rate(sum(1 for r in bucket if r[key]), len(bucket))

    metrics = [
        {
            "label": "Retrieval recall@5 — chart/table questions",
            "text": acc(visual_qs, "text_recall"),
            "visual": acc(visual_qs, "visual_recall"),
        },
        {
            "label": "Answer accuracy — chart/table questions",
            "text": acc(visual_qs, "text_ok"),
            "visual": acc(visual_qs, "visual_ok"),
        },
        {
            "label": "Answer accuracy — text-only questions",
            "text": acc(text_qs, "text_ok"),
            "visual": acc(text_qs, "visual_ok"),
        },
        {
            "label": "Answer accuracy — all answerable questions",
            "text": acc(answerable, "text_ok"),
            "visual": acc(answerable, "visual_ok"),
        },
    ]

    is_real = provider_name == "gemini"
    notes = (
        "Real run: visual answers generated by Gemini reading the page images."
        if is_real
        else "Offline run with deterministic mock providers: it validates the "
        "harness end-to-end, but the chart-reading gap only appears once a real "
        "VLM (Gemini) or ColPali retriever is enabled."
    )
    return {
        "generated_at": datetime.now(UTC).isoformat(),
        "is_real_run": is_real,
        "num_questions": n,
        "metrics": metrics,
        "guard_abstention_rate": rate(correct_abstentions, unanswerable_total),
        "notes": notes,
    }


def main() -> None:
    _configure_env()
    summary = asyncio.run(_evaluate())
    SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)
    SUMMARY_PATH.write_text(json.dumps(summary, indent=2))
    print(f"Wrote {SUMMARY_PATH}")
    for m in summary["metrics"]:
        print(f"  {m['label']:<48} text={m['text']:.0%}  visual={m['visual']:.0%}")
    print(f"  guard correct-abstention rate: {summary['guard_abstention_rate']:.0%}")


if __name__ == "__main__":
    main()
